# --- field extraction (tolerant) --------------------------------------------

def _finding_obj(finding) -> dict:
    """Normalise ONE finding into the locked findings.json shape, reading every
    field tolerantly so a real Finding or an ErroredFinding both work."""
    fid = getattr(finding, "id", None)
    present = bool(getattr(finding, "present", False))
    return {
        "id": fid,
        "name": getattr(finding, "name", None),
        "layer": getattr(finding, "layer", None),
        "present": present,
        "severity": getattr(finding, "severity", None),
        "owasp": getattr(finding, "owasp", None),
        "attempts": getattr(finding, "attempts", None),
        "primitives": list(getattr(finding, "primitives", []) or []),
        "evidence": getattr(finding, "evidence", {}) or {},
        # Fixed pointer to Section 6.1.2's own guidance -- only for a
        # CONFIRMED finding. Never null-coalesced
        # to "" -- None is the honest "nothing to point at" value, both for
        # an absent finding and for an id this mapping doesn't recognise.
        "general_guidance": _GENERAL_GUIDANCE.get(fid) if present else None,
    }


def _chain_obj(chain) -> dict:
    """Normalise ONE Chain into the locked findings.json shape. `reason` is only
    meaningful when the chain is NOT asserted; asserted chains carry null there."""
    asserted = bool(getattr(chain, "asserted", False))
    return {
        "id": getattr(chain, "id", None),
        "name": getattr(chain, "name", None),
        "asserted": asserted,
        "constituents": list(getattr(chain, "constituents", []) or []),
        "shared_artifact": getattr(chain, "shared_artifact", None),
        "provenance": getattr(chain, "provenance", {}) or {},
        "custody": list(getattr(chain, "custody", []) or []),
        "falsifiability_note": getattr(chain, "falsifiability_note", "") or "",
        "reason": (getattr(chain, "reason", "") or "") if not asserted else None,
    }


# --- markdown helpers -------------------------------------------------------

def _fmt_attempts(attempts) -> str:
    """Render an attempts value for the table/detail. None -> ASCII hyphen (web
    layer is deterministic and reports no ratio); otherwise the value as-is.

    ASCII only on purpose: report.md must render cleanly under any viewer
    encoding, so reporter-authored text uses no Unicode dashes."""
    if attempts is None:
        return "-"
    return str(attempts)


def _fmt_present(present: bool) -> str:
    return "yes" if present else "no"


def _summarize_evidence(evidence: dict) -> list[str]:
    """A compact, one-line-per-key summary of an evidence dict — never a raw dump.
    Long string values are truncated so the report stays examiner-readable."""
    if not evidence:
        return ["(no evidence captured)"]
    lines: list[str] = []
    for key, value in evidence.items():
        if isinstance(value, str):
            text = value.replace("\n", " ").strip()
            if len(text) > 160:
                text = text[:157] + "..."
        elif isinstance(value, (list, tuple)):
            text = f"[{len(value)} item(s)]"
        elif isinstance(value, dict):
            text = "{" + ", ".join(str(k) for k in value) + "}"
        else:
            text = str(value)
        lines.append(f"`{key}`: {text}")
    return lines


def _md_table_cell(text: str) -> str:
    """Escape a pipe so a value never breaks the markdown table."""
    return str(text).replace("|", "\\|")


# --- the pure builder -------------------------------------------------------

def build_report(findings: list, chains: list, meta: dict) -> tuple[dict, str]:
    """Build BOTH artefacts from the same data (§7.2). Returns
    (findings_json_obj, report_md_str). Pure — no file I/O, so both outputs are
    guaranteed to describe the identical in-memory state and can never disagree.

    meta carries: run_id, target, user, timestamp (ISO8601), and optionally
    duration_seconds (float, added by run_all.py's CI-gate work; omitted/None
    for callers that don't measure it, e.g. the GUI).
    """
    finding_objs = [_finding_obj(f) for f in findings]
    chain_objs = [_chain_obj(c) for c in chains]

    present_count = sum(1 for f in finding_objs if f["present"])
    asserted_count = sum(1 for c in chain_objs if c["asserted"])

    summary = {
        "findings_total": len(finding_objs),
        "findings_present": present_count,
        "chains_total": len(chain_objs),
        "chains_asserted": asserted_count,
    }

    findings_json_obj = {
        "run_id": meta.get("run_id"),
        "target": meta.get("target"),
        "user": meta.get("user"),
        "timestamp": meta.get("timestamp"),
        "duration_seconds": meta.get("duration_seconds"),
        "summary": summary,
        "findings": finding_objs,
        "chains": chain_objs,
    }

    report_md_str = _render_markdown(findings_json_obj)
    return findings_json_obj, report_md_str


def _render_markdown(data: dict) -> str:
    """Render report.md from the SAME normalised dict that becomes findings.json,
    so the two artefacts are structurally incapable of disagreeing."""
    summary = data["summary"]
    present = summary["findings_present"]
    total = summary["findings_total"]
    asserted = summary["chains_asserted"]
    chains_total = summary["chains_total"]

    out: list[str] = []

    # 1. Title + run header + one-line verdict.
    out.append("# AVSA Assessment Report")
    out.append("")
    out.append(f"- **run_id:** `{data['run_id']}`")
    out.append(f"- **target:** {data['target']}")
    out.append(f"- **user:** {data['user']}")
    out.append(f"- **timestamp:** {data['timestamp']}")
    if data.get("duration_seconds") is not None:
        out.append(f"- **duration:** {data['duration_seconds']}s")
    out.append("")
    out.append(
        f"**Verdict:** {present}/{total} vulnerabilities present; "
        f"{asserted}/{chains_total} cross-layer chains asserted."
    )
    out.append("")

    # 2. Methodology note.
    out.append("## Methodology")
    out.append("")
    out.append(
        "AVSA is a black-box scanner: it reaches DVAI only over HTTP and never "
        "reads the target's source. It works from a single low-privilege foothold "
        "(the `alice` account). LLM-layer detection is confirmation-based over N "
        "retries because the target is non-deterministic - a finding counts only "
        "if the invariant held on at least one attempt. Web-layer detection is "
        "deterministic. This report ASSESSES only; it never generates or "
        "prescribes a fix. A present finding is annotated with a fixed pointer "
        "to the dissertation's own general hardening guidance (Chapter 6) - not "
        "advice the scanner invents - and DVAI itself remains insecure by "
        "design and is never patched."
    )
    out.append("")

    # 3. Findings table.
    out.append("## Findings")
    out.append("")
    out.append("| id | name | layer | present | severity | OWASP | attempts | primitives |")
    out.append("|----|------|-------|---------|----------|-------|----------|------------|")
    for f in data["findings"]:
        prims = ", ".join(f["primitives"]) if f["primitives"] else "(none)"
        out.append(
            "| {id} | {name} | {layer} | {present} | {severity} | {owasp} | "
            "{attempts} | {primitives} |".format(
                id=_md_table_cell(f["id"]),
                name=_md_table_cell(f["name"]),
                layer=_md_table_cell(f["layer"]),
                present=_fmt_present(f["present"]),
                severity=_md_table_cell(f["severity"]),
                owasp=_md_table_cell(f["owasp"]),
                attempts=_md_table_cell(_fmt_attempts(f["attempts"])),
                primitives=_md_table_cell(prims),
            )
        )
    out.append("")

    # 4. Per-finding detail.
    out.append("## Finding detail")
    out.append("")
    for f in data["findings"]:
        out.append(f"### {f['name']} (`{f['id']}`)")
        out.append("")
        out.append(f"- **layer:** {f['layer']}  |  **present:** {_fmt_present(f['present'])}")
        out.append(f"- **severity:** {f['severity']}  |  **OWASP:** {f['owasp']}")
        out.append(f"- **attempts:** {_fmt_attempts(f['attempts'])}")
        note = _SEVERITY_NOTES.get(f["id"])
        if note:
            out.append(f"- **note:** {note}")
        out.append("- **evidence:**")
        for line in _summarize_evidence(f["evidence"]):
            out.append(f"  - {line}")
        guidance = f.get("general_guidance")
        if guidance:
            out.append(
                f"- **general guidance:** {guidance} "
                "(Chapter 6 of the dissertation discusses this in full.)"
            )
        out.append("")

    # 5. Chain view — the centrepiece (§7.6).
    out.append("## Cross-layer chains")
    out.append("")
    for c in data["chains"]:
        out.append(f"### {c['name']}")
        out.append("")
        if not c["asserted"]:
            out.append(f"**NOT asserted.** Reason: {c['reason']}")
            out.append("")
            continue
        out.append("**Asserted.**")
        out.append("")
        artifact = c["shared_artifact"]
        artifact_str = f"`{artifact}`" if artifact else "None (recon-overlap)"
        out.append(f"- **shared_artifact:** {artifact_str}")
        out.append(f"- **constituents:** {', '.join(c['constituents'])}")
        out.append("- **custody:**")
        # Plain bullets, NOT a markdown numbered list: the engine's custody
        # strings already start with "1. ", "2. ", ... so a numbered list here
        # would double the numbering ("1. 1. ..."). The engine numbers stay.
        for step in c["custody"]:
            out.append(f"  - {step}")
        out.append("- **provenance:**")
        for key, value in c["provenance"].items():
            out.append(f"  - `{key}`: {value}")
        out.append(f"- **falsifiability:** {c['falsifiability_note']}")
        out.append("")

    # 6. Limitations footer (honest).
    out.append("## Limitations")
    out.append("")
    out.append(
        "- **LLM non-determinism:** the LLM-layer findings and therefore the "
        "asserted chains may vary from run to run; a chain absent this run is not "
        "proof it cannot occur."
    )
    out.append(
        "- **Chain 1 execution:** the final firing of the payload in the victim's "
        "browser is evidenced by a manual, token-linked screenshot - it is not "
        "claimed by AVSA itself."
    )
    out.append(
        "- **Chain 2 strength:** Chain 2 is provenance-qualified (recon-overlap), "
        "not backed by an unforgeable per-run token as Chain 1 is."
    )
    out.append(
        "- **Honeypot:** `/admin/chats` is a 404 recon-bait honeypot (AVSA_SPEC "
        "Section 6.5); if the leak advertises it, it is recorded as a dead recon lead, "
        "never counted as a live attack strand."
    )
    out.append("")

    return "\n".join(out)


# --- disk writer ------------------------------------------------------------

def write_report(findings_json_obj: dict, report_md_str: str, out_dir: str = "output") -> tuple[str, str]:
    """Write both artefacts to `out_dir` (created if missing). Returns the two
    paths (json_path, md_path). The only part of the reporter that touches disk."""
    os.makedirs(out_dir, exist_ok=True)
    json_path = os.path.join(out_dir, "findings.json")
    md_path = os.path.join(out_dir, "report.md")

    with open(json_path, "w", encoding="utf-8") as fh:
        json.dump(findings_json_obj, fh, indent=2)
        fh.write("\n")

    with open(md_path, "w", encoding="utf-8") as fh:
        fh.write(report_md_str)

    return json_path, md_path
