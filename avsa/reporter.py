"""AVSA Reporter — one source of truth, two artefacts (Sprint 6, slice 5).

Takes the six findings and the two Chain verdicts that `run_all` already produces
and renders them into TWO files that can never disagree because they are built
from the SAME in-memory data (AVSA_SPEC §7.2):

    * output/findings.json — machine-readable ground truth (locked field names,
      discharging the §7.3 "[contract — confirm at build]" marker).
    * output/report.md     — human-readable, examiner-facing narrative (§7.4/§7.6),
      whose centrepiece is the per-chain custody story.

SCOPE — the reporter ASSESSES ONLY (§7.7). DVAI is insecure by design; this file
never generates or prescribes a fix. It describes what was found and how the
chain custody holds, nothing prescriptive. The one exception, added for the
reviewer feedback: a PRESENT finding is annotated with a fixed,
verbatim pointer to Section 6.1.2's own hardening guidance -- text the author
already wrote and the dissertation already defends, looked up by finding id,
never computed or invented at scan time. See _GENERAL_GUIDANCE below.

DESIGN — build_report is a PURE function (findings + chains + meta -> dict + str)
with no file I/O, so it is unit-testable with fabricated findings and no live bot.
write_report is the only part that touches disk. It reads every finding/chain
field tolerantly via getattr, so an ErroredFinding (or any Finding-shaped object)
renders without special-casing.
"""

from __future__ import annotations

import json
import os

# Findings we always expect (used only for the summary denominator wording; the
# actual list is whatever run_all hands us).
_FINDINGS_TOTAL = 6
_CHAINS_TOTAL = 2

